class TL:
    """Output-time map of a timeline (same rules as shortkit.edit.resolve: crossfade overlaps the previous
    clip by dur; flash / cut do not; freeze at src_t inserts hold; freeze at end appends hold)."""

    def __init__(self, segs: list[dict]):
        self.segs = segs
        self.out: dict[str, tuple[float, float]] = {}
        t = 0.0
        for k, s in enumerate(segs):
            tr = s.get("transition_in") or {}
            if k and tr.get("type") == "crossfade":
                t -= float(tr["dur"])
            d = (s["src_out"] - s["src_in"]) / float(s.get("speed", 1.0))
            d += float((s.get("freeze") or {}).get("hold") or 0.0)
            self.out[s["id"]] = (round(t, 4), round(t + d, 4))
            t += d
        self.duration = round(t, 4)

    def o(self, sid: str, src_t: float) -> float:
        s = next(x for x in self.segs if x["id"] == sid)
        t = self.out[sid][0] + (src_t - s["src_in"]) / float(s.get("speed", 1.0))
        fz = s.get("freeze") or {}
        if fz.get("at") == "src_t" and src_t > fz["src_t"]:
            t += float(fz["hold"])
        return round(t, 3)


