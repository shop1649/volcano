def cap(cid, role, text, start, end, src=None, src_t=None, kind="seen", note=None, pos=None, hl=None):
    c = {"id": cid, "role": role, "text": text, "start": round(float(start), 3), "end": round(float(end), 3)}
    if hl:
        c["highlight"] = list(hl)
    if pos is not None:
        c["pos"] = list(pos)
    if src is not None:
        g = {"kind": kind, "source": src, "src_t": src_t}
        if note:
            g["note"] = note
        c["grounding"] = g
    return c


def fx(fid, typ, t, desc, src, src_t, kind="action", ev_t=None):
    return {"id": fid, "type": typ, "t": t, "event": {"t": t if ev_t is None else ev_t, "desc": desc, "kind": kind,
                                                        "source": src, "src_t": src_t},
            "file": f"{SFX}/{typ}.wav"}


def arrow(did, start, end, x, y, reason, rotation=None):
    start, end = round(float(start), 3), round(float(end), 3)
    kf = {"t": 0.0, "x": x, "y": y}
    if rotation is not None:
        kf["rotation"] = rotation
    return {"id": did, "kind": "arrow", "start": start, "end": end, "keyframes": [kf], "reason": reason}


