def sha(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def ff(*args) -> None:
    subprocess.run(["ffmpeg", "-hide_banner", "-nostdin", "-v", "error", "-y", *map(str, args)], check=True)


def dump(p: Path, data, header: str = "") -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    txt = yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=140)
    p.write_text(header + txt, encoding="utf-8")


